_CURRENT_LANG = "en"

def detect_system_lang() -> str:
    """Определить системный язык пользователя (en, ru, es, etc.)."""
    try:
        sys_locale = locale.getdefaultlocale()[0] or ""
        code = sys_locale.split("_")[0].lower()
        if code in SUPPORTED_LANGUAGES:
            return code
    except Exception:
        pass
    env_lang = os.environ.get("LANG", "").split(".")[0].split("_")[0].lower()
    if env_lang in SUPPORTED_LANGUAGES:
        return env_lang
    return "en"

def set_lang(lang_code: str) -> None:
    global _CURRENT_LANG
    if lang_code in SUPPORTED_LANGUAGES:
        _CURRENT_LANG = lang_code

def get_lang() -> str:
    return _CURRENT_LANG

def t(key: str, **kwargs) -> str:
    """Получить локализованную строку по ключу."""
    lang_dict = STRINGS.get(_CURRENT_LANG, STRINGS["en"])
    val = lang_dict.get(key, STRINGS["en"].get(key, key))
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val

def translate_tip(text: str) -> str:
    """Динамический перевод текста всплывающей подсказки на текущий язык."""
    if not text:
        return ""
    cur = get_lang()
    if cur == "ru":
        return text
    if text in TOOLTIP_MAP:
        return TOOLTIP_MAP[text].get(cur, TOOLTIP_MAP[text].get("en", text))
    norm = text.replace("→", "->").replace("—", "-").strip()
    for k, v in TOOLTIP_MAP.items():
        if k.replace("→", "->").replace("—", "-").strip() == norm:
            return v.get(cur, v.get("en", text))
    if text in STRINGS.get(cur, {}):
        return STRINGS[cur][text]
    return text

def detect_text_language(text: str) -> str:
    """
    Быстрое эвристическое определение языка текста без тяжелых зависимостей.
    Поддерживает: zh, ja, hi, ru, и латиницу (en, es, de, fr).
    """
    if not text:
        return _CURRENT_LANG

    # Проверка символов восточных языков
    for char in text[:500]:
        cp = ord(char)
        # Китайские иероглифы (CJK Unified Ideographs)
        if 0x4E00 <= cp <= 0x9FFF:
            if any(0x3040 <= ord(c) <= 0x30FF for c in text[:500]):
                return "ja"
            return "zh"
        # Японская хирагана/катакана
        if 0x3040 <= cp <= 0x30FF:
            return "ja"
        # Деванагари (Хинди)
        if 0x0900 <= cp <= 0x097F:
            return "hi"
        # Кириллица (Русский)
        if 0x0400 <= cp <= 0x04FF:
            return "ru"

    # Для европейских языков на латинице смотрим специфические символы
    lower = text[:1000].lower()
    if any(c in lower for c in ["¿", "¡", "ñ", "á", "é", "í", "ó", "ú"]):
        return "es"
    if any(c in lower for c in ["ä", "ö", "ü", "ß"]):
        return "de"
    if any(c in lower for c in ["é", "è", "ê", "à", "ç", "ù", "œ"]):
        return "fr"

    return "en"
